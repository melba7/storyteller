import Foundation
import LofiAudio
import LofiScoreCore

/// A rendered placeholder track, loudness-normalised and ready to write.
public struct RenderedTrack: Sendable {
    public var recipe: PlaceholderRecipe
    public var audio: StereoBuffer
    /// Integrated loudness after normalisation, in LUFS.
    public var loudness: Double
    /// Estimated true peak, in dBFS.
    public var truePeak: Double
}

/// Makes the placeholder music library: one folder per mood with synthesised tracks and a
/// `library.json`, in the same layout Mo's real library will use. Nothing it writes belongs
/// in git; the demo app generates it on first launch.
public enum PlaceholderLibrary {
    /// Written into each track's `source`, so an existing folder can be recognised and reused.
    public static let generatorTag = "LofiPlaceholders v1"
    public static let license = "Generated by LofiScoreKit's placeholder synth; no rights reserved"

    /// Renders one recipe and brings it to `targetLoudness`, keeping the true peak under −1 dBFS.
    public static func render(
        _ recipe: PlaceholderRecipe,
        sampleRate: Double = 44_100,
        targetLoudness: Double = -16
    ) -> RenderedTrack {
        var audio = LofiSynth.render(recipe, sampleRate: sampleRate)
        var loudness = Loudness.integrated(audio)
        if loudness.isFinite {
            audio.scale(by: Float(Gain.linear(fromDB: targetLoudness - loudness)))
        }
        var peak = Loudness.truePeak(audio)
        if peak > -1 {
            limit(&audio, ceiling: Float(Gain.linear(fromDB: -1.2)))
            peak = Loudness.truePeak(audio)
        }
        loudness = Loudness.integrated(audio)
        return RenderedTrack(recipe: recipe, audio: audio, loudness: loudness, truePeak: peak)
    }

    /// The folder (relative to the library root) for a mood: "Calm", "Cozy", ...
    public static func folderName(for bucket: MoodBucket) -> String {
        bucket.rawValue.prefix(1).uppercased() + bucket.rawValue.dropFirst()
    }

    /// Renders every recipe into `folder` and writes `library.json`. Returns the manifest.
    @discardableResult
    public static func write(
        to folder: URL,
        recipes: [PlaceholderRecipe] = PlaceholderRecipe.defaults(),
        sampleRate: Double = 44_100,
        targetLoudness: Double = -16,
        progress: ((_ done: Int, _ total: Int, _ track: RenderedTrack) -> Void)? = nil
    ) throws -> LibraryManifest {
        let fileManager = FileManager.default
        try fileManager.createDirectory(at: folder, withIntermediateDirectories: true)
        var tracks: [LibraryTrack] = []
        for (index, recipe) in recipes.enumerated() {
            let rendered = render(recipe, sampleRate: sampleRate, targetLoudness: targetLoudness)
            let relative = "\(folderName(for: recipe.bucket))/\(recipe.id) \(Int(recipe.bpm))bpm.wav"
            let url = folder.appendingPathComponent(relative)
            try fileManager.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try WAVFile.write(rendered.audio, to: url)
            tracks.append(LibraryTrack(
                id: recipe.id,
                file: relative,
                bucket: recipe.bucket,
                valence: recipe.bucket.anchor.valence,
                arousal: recipe.bucket.anchor.arousal,
                intensity: recipe.intensity,
                bpm: recipe.bpm,
                beatsPerBar: 4,
                downbeat: 0,
                key: recipe.key,
                duration: rendered.audio.duration,
                loudness: (rendered.loudness * 10).rounded() / 10,
                truePeak: (rendered.truePeak * 10).rounded() / 10,
                source: generatorTag,
                license: license,
                prompt: recipe.summary,
                seed: LooseString(String(recipe.seed))
            ))
            progress?(index + 1, recipes.count, rendered)
        }
        let manifest = LibraryManifest(version: 1, targetLoudness: targetLoudness, tracks: tracks)
        try manifest.jsonData().write(to: folder.appendingPathComponent(LibraryManifest.fileName), options: .atomic)
        return manifest
    }

    /// Returns the placeholder library in `folder`, generating it first if it is missing,
    /// incomplete, or made by an older generator.
    public static func prepare(
        at folder: URL,
        recipes: [PlaceholderRecipe] = PlaceholderRecipe.defaults(),
        sampleRate: Double = 44_100,
        progress: ((_ done: Int, _ total: Int, _ track: RenderedTrack) -> Void)? = nil
    ) throws -> MusicLibrary {
        if let existing = try? MusicLibrary.load(from: folder), isCurrent(existing, recipes: recipes) {
            return existing
        }
        try write(to: folder, recipes: recipes, sampleRate: sampleRate, progress: progress)
        return try MusicLibrary.load(from: folder)
    }

    static func isCurrent(_ library: MusicLibrary, recipes: [PlaceholderRecipe]) -> Bool {
        let ids = Set(library.tracks.map(\.id))
        guard ids == Set(recipes.map(\.id)),
              library.tracks.allSatisfy({ $0.source == generatorTag })
        else { return false }
        return library.tracks.allSatisfy { FileManager.default.fileExists(atPath: library.url(for: $0).path) }
    }

    /// A soft knee above 70% of the ceiling, so peaks round off instead of clipping.
    static func limit(_ audio: inout StereoBuffer, ceiling: Float) {
        let knee = ceiling * 0.7
        let room = ceiling - knee
        func shape(_ x: Float) -> Float {
            let magnitude = abs(x)
            guard magnitude > knee else { return x }
            let shaped = knee + room * Float(tanh(Double((magnitude - knee) / room)))
            return x < 0 ? -shaped : shaped
        }
        for index in audio.left.indices {
            audio.left[index] = shape(audio.left[index])
            audio.right[index] = shape(audio.right[index])
        }
    }
}
