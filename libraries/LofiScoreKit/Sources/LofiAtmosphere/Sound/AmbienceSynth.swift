import Foundation
import LofiDirector
import LofiPlaceholders

/// Synthesised stand-ins for every ambient sound, so the atmosphere works before real
/// recordings are imported (and in tests). They are rough sketches made from filtered
/// noise and simple events (droplets, crackles, chirps), rendered as seamless loops and
/// levelled to the same loudness. Real recordings replace them sound by sound.
public enum AmbienceSynth {
    public static let generatorTag = "LofiAtmosphere synth v1"
    public static let license = "Generated by LofiScoreKit's ambience synth; no rights reserved"
    public static let targetLoudness = -23.0

    /// Renders one sound as a seamless stereo loop.
    public static func render(_ sound: AmbientSound, seconds: Double = 30, sampleRate: Double = 32_000, seed: UInt64 = 1) -> StereoBuffer {
        let crossfade = min(3, seconds / 4)
        var s = Sketch(seconds: seconds + crossfade, rate: sampleRate, seed: seed &+ StableHash.fnv1a(sound.rawValue))
        s.draw(sound)
        var buffer = loop(s.out, crossfade: crossfade)
        let loudness = Loudness.integrated(buffer)
        if loudness.isFinite {
            buffer.scale(by: Float(pow(10, (targetLoudness - loudness) / 20)))
        }
        softLimit(&buffer, ceiling: 0.7)
        return buffer
    }

    /// Writes every sound (or `sounds`) into `folder` as WAV with a `sounds.json`, unless
    /// a current set is already there. Returns the library.
    public static func prepare(
        at folder: URL,
        sounds: [AmbientSound] = AmbientSound.allCases,
        seconds: Double = 30,
        sampleRate: Double = 32_000
    ) throws -> AmbienceLibrary {
        if let existing = try? AmbienceLibrary.load(from: folder),
           Set(existing.recordings.map(\.sound)) == Set(sounds),
           existing.recordings.allSatisfy({ $0.source == generatorTag }) {
            return existing
        }
        try? FileManager.default.removeItem(at: folder)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        var recordings: [AmbienceRecording] = []
        for sound in sounds {
            let audio = render(sound, seconds: seconds, sampleRate: sampleRate)
            let file = "\(sound.folderName)/\(sound.rawValue)-synth.wav"
            let url = folder.appendingPathComponent(file)
            try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try WAVFile.write(audio, to: url)
            recordings.append(AmbienceRecording(
                id: "\(sound.rawValue)/synth", file: file, sound: sound,
                loudness: Loudness.integrated(audio), duration: audio.duration,
                title: "\(sound.folderName) (synthesised stand-in)", author: "LofiScoreKit",
                source: generatorTag, license: license
            ))
        }
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        try encoder.encode(AmbienceLibrary.Manifest(sounds: recordings))
            .write(to: folder.appendingPathComponent(AmbienceLibrary.manifestName), options: .atomic)
        return try AmbienceLibrary.load(from: folder)
    }

    /// Crossfades the last `crossfade` seconds into the start, so the end runs straight
    /// into the beginning.
    static func loop(_ input: StereoBuffer, crossfade: Double) -> StereoBuffer {
        let fade = Int(crossfade * input.sampleRate)
        let length = input.frames - fade
        guard fade > 0, length > fade else { return input }
        var out = StereoBuffer(frames: length, sampleRate: input.sampleRate)
        for i in 0..<length {
            out.left[i] = input.left[i]
            out.right[i] = input.right[i]
        }
        for i in 0..<fade {
            let x = Double(i) / Double(fade)
            let fadeIn = Float(sin(x * .pi / 2))
            let fadeOut = Float(cos(x * .pi / 2))
            out.left[i] = input.left[i] * fadeIn + input.left[length + i] * fadeOut
            out.right[i] = input.right[i] * fadeIn + input.right[length + i] * fadeOut
        }
        return out
    }

    static func softLimit(_ audio: inout StereoBuffer, ceiling: Float) {
        let knee = ceiling * 0.7
        let room = ceiling - knee
        func shape(_ x: Float) -> Float {
            let magnitude = abs(x)
            guard magnitude > knee else { return x }
            let shaped = knee + room * Float(tanh(Double((magnitude - knee) / room)))
            return x < 0 ? -shaped : shaped
        }
        for i in audio.left.indices {
            audio.left[i] = shape(audio.left[i])
            audio.right[i] = shape(audio.right[i])
        }
    }
}

/// The drawing board: a stereo buffer and the few tools the sketches are made of.
private struct Sketch {
    var out: StereoBuffer
    var rng: SplitMix64
    let rate: Double
    var frames: Int { out.frames }

    init(seconds: Double, rate: Double, seed: UInt64) {
        self.rate = rate
        out = StereoBuffer(frames: Int(seconds * rate), sampleRate: rate)
        rng = SplitMix64(seed: seed)
    }

    // MARK: Signals

    mutating func white() -> [Float] {
        (0..<frames).map { _ in Float(rng.nextUnit() * 2 - 1) }
    }

    mutating func brown() -> [Float] {
        var y: Float = 0
        return white().map { x in
            y = (y + 0.02 * x) * 0.998
            return y * 8
        }
    }

    /// A smooth random control signal between 0 and 1, changing about `hz` times a second.
    mutating func wander(_ hz: Double) -> [Float] {
        let step = max(1, Int(rate / max(0.01, hz)))
        var points: [Float] = []
        for _ in 0...(frames / step + 2) { points.append(Float(rng.nextUnit())) }
        return (0..<frames).map { i in
            let p = i / step
            let x = Float(i % step) / Float(step)
            let s = x * x * (3 - 2 * x)
            return points[p] * (1 - s) + points[p + 1] * s
        }
    }

    func lowpass(_ x: [Float], _ cutoff: Double) -> [Float] {
        let a = Float(1 - exp(-2 * .pi * cutoff / rate))
        var y: Float = 0
        return x.map { v in
            y += a * (v - y)
            return y
        }
    }

    func highpass(_ x: [Float], _ cutoff: Double) -> [Float] {
        let low = lowpass(x, cutoff)
        return zip(x, low).map { $0 - $1 }
    }

    /// A band-pass whose centre follows `center` (Hz per sample, or one fixed value).
    func bandpass(_ x: [Float], center: (Int) -> Double, q: Double) -> [Float] {
        var x1: Float = 0, x2: Float = 0, y1: Float = 0, y2: Float = 0
        var b0: Float = 0, b2: Float = 0, a1: Float = 0, a2: Float = 0
        var out = [Float](repeating: 0, count: x.count)
        for i in x.indices {
            if i % 64 == 0 {
                let w = 2 * .pi * min(center(i), rate * 0.45) / rate
                let alpha = sin(w) / (2 * q)
                let a0 = 1 + alpha
                b0 = Float(alpha / a0)
                b2 = Float(-alpha / a0)
                a1 = Float(-2 * cos(w) / a0)
                a2 = Float((1 - alpha) / a0)
            }
            let y = b0 * x[i] + b2 * x2 - a1 * y1 - a2 * y2
            x2 = x1
            x1 = x[i]
            y2 = y1
            y1 = y
            out[i] = y
        }
        return out
    }

    // MARK: Mixing

    mutating func add(_ signal: [Float], gain: Float, pan: Float = 0) {
        let l = gain * sqrt((1 - pan) / 2) * 1.414
        let r = gain * sqrt((1 + pan) / 2) * 1.414
        for i in 0..<min(signal.count, frames) {
            out.left[i] += signal[i] * l
            out.right[i] += signal[i] * r
        }
    }

    /// The same kind of bed in each ear, made separately, so it sounds wide.
    mutating func addWide(gain: Float, _ make: (inout Sketch) -> [Float]) {
        let left = make(&self)
        let right = make(&self)
        for i in 0..<frames {
            out.left[i] += left[i] * gain
            out.right[i] += right[i] * gain
        }
    }

    /// Calls `event` at random times, about `perSecond` times a second.
    mutating func scatter(perSecond: Double, _ event: (inout Sketch, Int) -> Void) {
        var t = 0.0
        let duration = Double(frames) / rate
        while true {
            t += -log(max(1e-9, 1 - rng.nextUnit())) / perSecond
            guard t < duration else { break }
            event(&self, Int(t * rate))
        }
    }

    /// Adds `length` seconds made by `sample(seconds since start)` at `start`.
    mutating func place(at start: Int, length: Double, gain: Float, pan: Float, _ sample: (Double) -> Double) {
        let count = Int(length * rate)
        let l = gain * sqrt((1 - pan) / 2) * 1.414
        let r = gain * sqrt((1 + pan) / 2) * 1.414
        for k in 0..<count {
            let i = start + k
            guard i < frames else { break }
            let v = Float(sample(Double(k) / rate))
            guard i >= 0 else { continue }
            out.left[i] += v * l
            out.right[i] += v * r
        }
    }

    mutating func randomPan(_ width: Float = 0.8) -> Float { Float(rng.nextUnit() * 2 - 1) * width }
    mutating func uniform(_ low: Double, _ high: Double) -> Double { low + (high - low) * rng.nextUnit() }

    // MARK: Events

    mutating func droplet(at i: Int, gain: Float, pitch: Double) {
        let pan = randomPan()
        place(at: i, length: 0.06, gain: gain, pan: pan) { t in
            sin(2 * .pi * pitch * (1 + 2 * t / 0.06) * t) * exp(-t * 90)
        }
    }

    mutating func crackle(at i: Int, gain: Float, decay: Double) {
        let pan = randomPan(0.5)
        var seed = rng.next()
        place(at: i, length: 6 / decay, gain: gain, pan: pan) { t in
            seed = seed &* 6364136223846793005 &+ 1442695040888963407
            let noise = Double(Int64(bitPattern: seed)) / Double(Int64.max)
            return noise * exp(-t * decay)
        }
    }

    mutating func chirp(at i: Int, gain: Float, from f0: Double, to f1: Double, length: Double, pan: Float) {
        place(at: i, length: length, gain: gain, pan: pan) { t in
            let x = t / length
            let f = f0 + (f1 - f0) * x
            return sin(2 * .pi * f * t) * sin(.pi * x)
        }
    }

    mutating func tone(at i: Int, gain: Float, frequency: Double, length: Double, attack: Double, pan: Float) {
        place(at: i, length: length, gain: gain, pan: pan) { t in
            let envelope = min(1, t / attack) * exp(-3 * t / length)
            return sin(2 * .pi * frequency * t) * envelope
        }
    }

    // MARK: The sketches

    mutating func draw(_ sound: AmbientSound) {
        switch sound {
        case .rain, .heavyRain, .rainIndoors:
            let heavy = sound == .heavyRain
            let indoors = sound == .rainIndoors
            addWide(gain: heavy ? 0.5 : 0.3) { s in
                let n = s.highpass(s.white(), 400)
                return indoors ? s.lowpass(n, 1400) : s.lowpass(n, heavy ? 9000 : 6000)
            }
            scatter(perSecond: heavy ? 90 : 40) { s, i in
                s.droplet(at: i, gain: Float(s.uniform(0.02, indoors ? 0.05 : 0.12)), pitch: s.uniform(indoors ? 900 : 1800, indoors ? 1800 : 4500))
            }
            if heavy { addWide(gain: 0.4) { s in s.lowpass(s.brown(), 200) } }
        case .thunder:
            addWide(gain: 0.05) { s in s.lowpass(s.brown(), 120) }
            scatter(perSecond: 1.0 / 9) { s, i in
                var seed = s.rng.next()
                let length = s.uniform(4, 7)
                s.place(at: i, length: length, gain: 1.4, pan: s.randomPan(0.4)) { t in
                    seed = seed &* 6364136223846793005 &+ 1442695040888963407
                    let noise = Double(Int64(bitPattern: seed)) / Double(Int64.max)
                    let envelope = min(1, t / 1.2) * exp(-2.2 * t / length) * (0.7 + 0.3 * sin(t * 5.3))
                    return noise * envelope
                }
            }
            let rumble = lowpass(lowpass(out.left, 160), 160)
            let rumbleRight = lowpass(lowpass(out.right, 160), 160)
            out.left = rumble
            out.right = rumbleRight
        case .wind, .strongWind, .snow:
            let strong = sound == .strongWind
            let snow = sound == .snow
            addWide(gain: snow ? 0.6 : (strong ? 1.2 : 0.9)) { s in
                let swell = s.wander(strong ? 0.4 : 0.15)
                let noise = s.white()
                let band = s.bandpass(noise, center: { i in (snow ? 180 : (strong ? 500 : 320)) + Double(swell[i]) * (snow ? 220 : (strong ? 900 : 500)) }, q: snow ? 0.6 : (strong ? 1.6 : 0.9))
                return zip(band, swell).map { $0 * (0.25 + $1) }
            }
            if snow {
                out.left = lowpass(out.left, 900)
                out.right = lowpass(out.right, 900)
            }
        case .fireplace, .campfire:
            let camp = sound == .campfire
            addWide(gain: camp ? 0.25 : 0.4) { s in s.lowpass(s.brown(), camp ? 300 : 180) }
            scatter(perSecond: camp ? 14 : 9) { s, i in
                s.crackle(at: i, gain: Float(s.uniform(0.05, 0.25)), decay: s.uniform(250, 900))
            }
            scatter(perSecond: 0.4) { s, i in
                s.crackle(at: i, gain: Float(s.uniform(0.3, 0.6)), decay: s.uniform(120, 300))
            }
            if camp { addWide(gain: 0.15) { s in s.bandpass(s.white(), center: { _ in 400 }, q: 0.7) } }
        case .seaShore, .openSea:
            let open = sound == .openSea
            for side in [Float(-0.6), 0.6] {
                var envelope = [Float](repeating: 0, count: frames)
                var t = Int(uniform(0, 2) * rate)
                while t < frames {
                    let period = open ? uniform(2.5, 4) : uniform(7, 11)
                    let length = Int(period * rate)
                    for k in 0..<length where t + k < frames {
                        let x = Double(k) / Double(length)
                        envelope[t + k] = Float(open ? sin(.pi * x) : (x < 0.25 ? x / 0.25 : exp(-(x - 0.25) * 4)))
                    }
                    t += length
                }
                let noise = lowpass(white(), open ? 900 : 2500)
                add(zip(noise, envelope).map { $0 * (0.15 + $1) }, gain: open ? 0.6 : 0.9, pan: side)
            }
            if open {
                scatter(perSecond: 0.5) { s, i in s.tone(at: i, gain: 0.15, frequency: s.uniform(60, 90), length: 0.5, attack: 0.02, pan: s.randomPan(0.3)) }
            }
        case .river:
            addWide(gain: 0.5) { s in
                let wobble = s.wander(3)
                return s.bandpass(s.white(), center: { i in 500 + Double(wobble[i]) * 1500 }, q: 0.8)
            }
            scatter(perSecond: 25) { s, i in
                s.chirp(at: i, gain: Float(s.uniform(0.02, 0.06)), from: s.uniform(300, 700), to: s.uniform(800, 1600), length: s.uniform(0.02, 0.06), pan: s.randomPan())
            }
        case .dripping:
            addWide(gain: 0.03) { s in s.lowpass(s.brown(), 400) }
            scatter(perSecond: 1.3) { s, i in
                let pitch = s.uniform(700, 1600)
                let gain = Float(s.uniform(0.15, 0.4))
                let pan = s.randomPan()
                for echo in 0..<4 {
                    let delay = Int(Double(echo) * 0.11 * s.rate)
                    s.place(at: i + delay, length: 0.08, gain: gain * pow(0.45, Float(echo)), pan: pan * (echo % 2 == 0 ? 1 : -1)) { t in
                        sin(2 * .pi * pitch * (1 + 3 * t / 0.08) * t) * exp(-t * 60)
                    }
                }
            }
        case .forest, .birdsong:
            let leaves = sound == .forest
            addWide(gain: leaves ? 0.35 : 0.12) { s in
                let sway = s.wander(0.2)
                return zip(s.bandpass(s.white(), center: { _ in 2200 }, q: 0.5), sway).map { $0 * (0.2 + $1) }
            }
            scatter(perSecond: leaves ? 0.5 : 1.4) { s, i in
                let notes = Int(s.uniform(2, 6))
                let base = s.uniform(2200, 4200)
                let pan = s.randomPan()
                let gain = Float(s.uniform(0.04, leaves ? 0.08 : 0.15))
                for n in 0..<notes {
                    let start = i + Int(Double(n) * 0.13 * s.rate)
                    s.chirp(at: start, gain: gain, from: base * s.uniform(0.9, 1.1), to: base * s.uniform(1.2, 1.5), length: 0.08, pan: pan)
                }
            }
        case .nightInsects, .nightForest, .swamp:
            let crickets = sound == .nightInsects ? 4 : (sound == .swamp ? 2 : 1)
            for _ in 0..<crickets {
                let pitch = uniform(4000, 5200)
                let rateHz = uniform(1.5, 3)
                let pan = randomPan()
                let gain = Float(uniform(0.02, 0.05))
                var t = uniform(0, 1)
                while t * rate < Double(frames) {
                    for pulse in 0..<3 {
                        let start = Int((t + Double(pulse) * 0.025) * rate)
                        place(at: start, length: 0.015, gain: gain, pan: pan) { u in sin(2 * .pi * pitch * u) * sin(.pi * u / 0.015) }
                    }
                    t += 1 / rateHz
                }
            }
            addWide(gain: 0.06) { s in s.lowpass(s.white(), 1200) }
            if sound == .nightForest {
                scatter(perSecond: 1.0 / 10) { s, i in
                    let pan = s.randomPan(0.6)
                    s.tone(at: i, gain: 0.12, frequency: 380, length: 0.45, attack: 0.08, pan: pan)
                    s.tone(at: i + Int(0.6 * s.rate), gain: 0.1, frequency: 340, length: 0.7, attack: 0.1, pan: pan)
                }
            }
            if sound == .swamp {
                scatter(perSecond: 1.5) { s, i in
                    let pitch = s.uniform(90, 160)
                    let pan = s.randomPan()
                    for k in 0..<Int(s.uniform(3, 7)) {
                        s.place(at: i + Int(Double(k) * 0.05 * s.rate), length: 0.04, gain: 0.08, pan: pan) { t in
                            sin(2 * .pi * pitch * t) * sin(2 * .pi * pitch * 3.1 * t) * sin(.pi * t / 0.04)
                        }
                    }
                }
            }
        case .crowd:
            // A murmur of many voices: noise through moving vowel formants, a syllable at a time.
            for _ in 0..<14 {
                let pan = randomPan(0.9)
                let gain = Float(uniform(0.3, 0.7))
                let syllable = uniform(0.16, 0.26)
                var formant1 = [Double](repeating: 500, count: frames)
                var formant2 = [Double](repeating: 1500, count: frames)
                var envelope = [Float](repeating: 0, count: frames)
                var t = 0
                let pitch = uniform(0.8, 1.25)
                while t < frames {
                    let length = Int(syllable * uniform(0.7, 1.3) * rate)
                    let f1 = uniform(300, 800) * pitch
                    let f2 = uniform(900, 2200) * pitch
                    let talking = rng.nextUnit() < 0.75
                    for k in 0..<length where t + k < frames {
                        formant1[t + k] = f1
                        formant2[t + k] = f2
                        envelope[t + k] = talking ? Float(sin(.pi * Double(k) / Double(length))) : 0
                    }
                    t += length
                }
                let source = white()
                let a = bandpass(source, center: { formant1[$0] }, q: 5)
                let b = bandpass(source, center: { formant2[$0] }, q: 7)
                add((0..<frames).map { (a[$0] + 0.6 * b[$0]) * envelope[$0] }, gain: gain, pan: pan)
            }
            out.left = lowpass(out.left, 2500)
            out.right = lowpass(out.right, 2500)
        case .city:
            addWide(gain: 0.6) { s in s.lowpass(s.brown(), 250) }
            scatter(perSecond: 0.25) { s, i in
                let length = s.uniform(5, 9)
                let pan = s.randomPan()
                var seed = s.rng.next()
                s.place(at: i, length: length, gain: 0.25, pan: pan) { t in
                    seed = seed &* 6364136223846793005 &+ 1442695040888963407
                    let noise = Double(Int64(bitPattern: seed)) / Double(Int64.max)
                    return noise * sin(.pi * t / length) * sin(.pi * t / length)
                }
            }
            out.left = lowpass(out.left, 1200)
            out.right = lowpass(out.right, 1200)
        case .oldTown, .horses:
            let riding = sound == .horses
            addWide(gain: riding ? 0.35 : 0.15) { s in s.lowpass(s.brown(), 220) }
            let pattern: [Double] = riding ? [0, 0.18, 0.4, 0.58] : [0, 0.25]
            let stride = riding ? 0.8 : 1.6
            var t = 0.0
            let duration = Double(frames) / rate
            while t < duration {
                for offset in pattern {
                    let start = Int((t + offset + uniform(-0.01, 0.01)) * rate)
                    let pitch = uniform(700, 1100)
                    place(at: start, length: 0.05, gain: riding ? 0.25 : 0.12, pan: riding ? 0 : -0.4) { u in sin(2 * .pi * pitch * u) * exp(-u * 120) }
                }
                t += stride
                if !riding, rng.nextUnit() < 0.1 { t += uniform(2, 5) }
            }
            if !riding {
                scatter(perSecond: 1.0 / 14) { s, i in
                    let pan = s.randomPan(0.7)
                    for partial in [1.0, 2.4, 3.0, 4.5] {
                        s.tone(at: i, gain: Float(0.05 / partial), frequency: 440 * partial, length: 3, attack: 0.005, pan: pan)
                    }
                }
            }
        case .train:
            addWide(gain: 0.5) { s in s.lowpass(s.brown(), 160) }
            addWide(gain: 0.08) { s in s.bandpass(s.white(), center: { _ in 3000 }, q: 0.5) }
            var t = 0.0
            while t * rate < Double(frames) {
                for offset in [0.0, 0.12] {
                    place(at: Int((t + offset) * rate), length: 0.08, gain: 0.35, pan: 0) { u in sin(2 * .pi * 140 * u) * exp(-u * 60) }
                }
                t += 1.1
            }
        case .ship:
            addWide(gain: 0.25) { s in s.lowpass(s.white(), 700) }
            scatter(perSecond: 0.6) { s, i in
                let base = s.uniform(180, 420)
                let length = s.uniform(0.4, 1.1)
                s.place(at: i, length: length, gain: 0.07, pan: s.randomPan()) { t in
                    let f = base * (1 + 0.2 * sin(2 * .pi * 1.3 * t))
                    return sin(2 * .pi * f * t) * (1 + 0.5 * sin(2 * .pi * 31 * t)) * sin(.pi * t / length)
                }
            }
        case .machinery:
            let drift = wander(0.1)
            add((0..<frames).map { i in
                let t = Double(i) / rate
                let h = sin(2 * .pi * 55 * t) + 0.6 * sin(2 * .pi * 110 * t) + 0.3 * sin(2 * .pi * 165.4 * t)
                return Float(h) * (0.8 + 0.2 * drift[i])
            }, gain: 0.15)
            addWide(gain: 0.12) { s in s.bandpass(s.white(), center: { _ in 600 }, q: 0.6) }
        case .clock:
            addWide(gain: 0.02) { s in s.lowpass(s.brown(), 300) }
            var t = 0.0
            var tick = true
            while t * rate < Double(frames) {
                let pitch = tick ? 3200.0 : 2600.0
                place(at: Int(t * rate), length: 0.02, gain: 0.25, pan: -0.2) { u in sin(2 * .pi * pitch * u) * exp(-u * 400) }
                tick.toggle()
                t += 1
            }
        }
    }
}
